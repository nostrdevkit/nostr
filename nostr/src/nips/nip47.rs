#[cfg(feature = "std")]
fn validate_wallet_event(
    uri: &NostrWalletConnectUri,
    event: &Event,
    allowed_kinds: &[Kind],
) -> Result<(), Error> {
    // ECDH authenticates the supplied peer, so bind that peer to the configured wallet first.
    if event.pubkey != uri.public_key {
        return Err(Error::with_static_message(
            ErrorKind::Invalid,
            "wallet event author mismatch",
        ));
    }

    if !allowed_kinds.contains(&event.kind) {
        return Err(Error::with_static_message(
            ErrorKind::Invalid,
            "invalid wallet event kind",
        ));
    }

    if !event.verify_id() {
        return Err(Error::with_static_message(
            ErrorKind::Invalid,
            "invalid wallet event ID",
        ));
    }

    if !event.verify_signature() {
        return Err(Error::with_static_message(
            ErrorKind::Invalid,
            "invalid wallet event signature",
        ));
    }

    Ok(())
}

/// NIP47 Response Error codes
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize)]
pub enum ErrorCode {
    ///  The client is sending commands too fast.
    #[serde(rename = "RATE_LIMITED")]
    RateLimited,
    /// The command is not known of is intentionally not implemented
    #[serde(rename = "NOT_IMPLEMENTED")]
    NotImplemented,
    /// The wallet does not have enough funds to cover a fee reserve or the payment amount
    #[serde(rename = "INSUFFICIENT_BALANCE")]
    InsufficientBalance,
    /// The payment failed. This may be due to a timeout, exhausting all routes, insufficient capacity or similar.
    #[serde(rename = "PAYMENT_FAILED")]
    PaymentFailed,
    /// The invoice could not be found by the given parameters.
    #[serde(rename = "NOT_FOUND")]
    NotFound,
    /// The wallet has exceeded its spending quota
    #[serde(rename = "QUOTA_EXCEEDED")]
    QuotaExceeded,
    /// This public key is not allowed to do this operation
    #[serde(rename = "RESTRICTED")]
    Restricted,
    /// This public key has no wallet connected
    #[serde(rename = "UNAUTHORIZED")]
    Unauthorized,
    /// The URI or another parameter is invalid
    #[serde(rename = "BAD_REQUEST")]
    BadRequest,
    /// The wallet cannot select a supported payment instruction
    #[serde(rename = "UNSUPPORTED_PAYMENT_INSTRUCTION")]
    UnsupportedPaymentInstruction,
    /// The selected instruction uses a different Bitcoin network
    #[serde(rename = "UNSUPPORTED_NETWORK")]
    UnsupportedNetwork,
    /// No route fit the `max_fee` budget and no payment was attempted
    #[serde(rename = "FEE_LIMIT_EXCEEDED")]
    FeeLimitExceeded,
    /// An internal error
    #[serde(rename = "INTERNAL")]
    Internal,
    /// Other error
    #[serde(rename = "OTHER")]
    Other,
}

