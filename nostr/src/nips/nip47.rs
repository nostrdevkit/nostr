// Prevent direct construction; all instances must come from the constants
// generated by the macro below.
/// Bitflags of NIP-47 ciphers supported by a wallet.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct Nip47Ciphers(u32);

macro_rules! define_ciphers {
    (
        $(
            $const_name:ident : $bit:expr => $str:expr =>
                encrypt: $enc_fn:path,
                decrypt: $dec_fn:path,
        )*
    ) => {
        impl Nip47Ciphers {
            $(
                #[doc = concat!("`", $str, "` ", "cipher")]
                pub const $const_name: Self = Self(1 << $bit);
            )*

            /// Ordered list of all ciphers, highest priority first.
            const ALL: &[(Self, &str)] = &[
                $((Self::$const_name, $str),)*
            ];

            /// Encrypt the given string using the most preferred cipher available
            #[cfg(all(feature = "std", feature = "os-rng"))]
            #[inline]
            pub fn encrypt(
                &self,
                secret_key: &SecretKey,
                public_key: &PublicKey,
                content: &String,
            ) -> Result<String, Error> {
                $(
                    if self.has(Self::$const_name) {
                        return $enc_fn(secret_key, public_key, content);
                    }
                )*
                unreachable!("unknown ciphers. This should never happen")
            }

            /// Decrypt the given string using the most preferred cipher available
            #[inline]
            pub fn decrypt(
                &self,
                secret_key: &SecretKey,
                public_key: &PublicKey,
                content: &String,
            ) -> Result<String, Error> {
                $(
                    if self.has(Self::$const_name) {
                        return $dec_fn(secret_key, public_key, content);
                    }
                )*
                unreachable!("unknown ciphers. This should never happen")
            }
        }
    };
}

#[cfg(all(feature = "std", feature = "os-rng"))]
#[inline]
fn nip44_v2_encrypt(
    secret_key: &SecretKey,
    public_key: &PublicKey,
    data: &str,
) -> Result<String, Error> {
    nip44::encrypt(secret_key, public_key, data, nip44::Version::V2)
}

// NOTE: List ciphers from newest (highest priority) to oldest.
define_ciphers![
    NIP44V2 : 1 => "nip44_v2" =>
        encrypt: nip44_v2_encrypt,
        decrypt: nip44::decrypt,

    NIP04 : 0 => "nip04" =>
        encrypt: nip04::encrypt,
        decrypt: nip04::decrypt,
];

impl Nip47Ciphers {
    /// Resolves a raw `u32` value into a cipher, if one exists.
    pub fn from_u32(inner: u32) -> Option<Self> {
        for (cipher, _) in Self::ALL {
            if cipher.0 == inner {
                return Some(*cipher);
            }
        }
        None
    }

    /// The latest cipher value as its raw inner `u32`.
    #[inline]
    pub fn as_u32(&self) -> u32 {
        self.latest().0
    }

    /// Combine two sets of supported ciphers.
    ///
    /// Used to build the wallet info `encryption` tag.
    #[inline]
    #[must_use]
    pub const fn add(mut self, other: Self) -> Self {
        self.0 |= other.0;
        self
    }

    /// Returns `true` if this ciphers contains `other`.
    ///
    /// When `other` is a single cipher, this simply tests for its presence. If
    /// you pass a combination of multiple ciphers, the method returns `true` as
    /// long as **at least one** of them is present.
    #[inline]
    pub const fn has(&self, other: Self) -> bool {
        self.0 & other.0 != 0
    }

    /// Returns the latest cipher from the ciphers
    #[inline]
    #[must_use]
    pub fn latest(&self) -> Self {
        // Return the first cipher, the latest one added
        for &(flag, _) in Self::ALL {
            if self.has(flag) {
                return flag;
            }
        }
        unreachable!("unknown ciphers. This should never happen")
    }
}

impl fmt::Display for Nip47Ciphers {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        let parts: Vec<_> = Self::ALL
            .iter()
            .filter(|&&(flag, _)| self.has(flag))
            .map(|&(_, s)| s)
            .collect();
        write!(f, "{}", parts.join(" "))
    }
}

impl FromStr for Nip47Ciphers {
    type Err = Error;

    fn from_str(s: &str) -> Result<Self, Self::Err> {
        let trimmed = s.trim();
        if trimmed.is_empty() {
            return Err(invalid_value("empty encryption tag"));
        }
        let mut this = Self(0);

        for etype in trimmed.split_whitespace() {
            let flag = Self::ALL
                .iter()
                .find(|&&(_, name)| name == etype)
                .map(|&(flag, _)| flag);

            // Ignore unknown potentially new ciphers
            match flag {
                Some(cipher) => this = this.add(cipher),
                None => continue,
            }
        }

        // Return an error if no known cipher found
        if this.0 == 0 {
            return Err(Error::with_static_message(
                ErrorKind::Other,
                "No known cipher in `encryption` tag",
            ));
        }

        Ok(this)
    }
}

/// Standardized NIP-47 tags
///
/// <https://github.com/nostr-protocol/nips/blob/master/47.md>
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum Nip47Tag {
    /// `encryption` tag
    Encryption(Nip47Ciphers),
}

impl_tag_codec_conversions! {
    Nip47Tag,
    fn parse(tag) {
        let mut iter = tag.into_iter();

        let kind: S = iter.next().ok_or(missing_tag_kind())?;

        match kind.as_ref() {
            ENCRYPTION => Ok(Self::Encryption(take_and_parse_from_str(
                &mut iter,
                "encryption",
            )?)),
            _ => Err(unknown_tag()),
        }
    }

    fn to_tag(&self) {
        match self {
            Nip47Tag::Encryption(et) => Tag::new(vec![String::from(ENCRYPTION), et.to_string()]),
        }
    }
}

